"""Generate results/SUMMARY.md from the raw JSON results (counted fields only)."""
import json
import os

from common import RESULTS

L = ["# Experimental summary (generated by `experiments/analyze.py`)", "",
     "Every number below is read from `experiments/results/*.json`. Counted fields are deterministic; "
     "wall-clock fields (suffix `_s`) are not reported here.", ""]
J = lambda n: json.load(open(os.path.join(RESULTS, n)))["data"]

d = J("exp001.json")
L += ["## GIN-EXP-001 Numerals and the successor grammar", "",
      f"- Non-injectivity = leading zeros, formula `L − |addr(n)| + 1` words: " +
      ", ".join(f"{k}: {'holds' if v['all_match_formula'] else 'FAILS'}" for k, v in d["non_injectivity"].items()) + ".",
      "- Bijective numeration: " + "; ".join(f"{k}: {v['words']} words, {v['collisions']} collisions, initial segment = {v['values_form_initial_segment']}" for k, v in d["bijective"].items()) + ".",
      f"- Heap conjugacy (bijective base 2 ↔ CGT heap, shifted by 1): {d['heap_conjugacy']['mismatches']} mismatches for n < {d['heap_conjugacy']['checked_n_below']}.",
      f"- Two's complement = truncated 2-adic expansion: {d['twos_complement']['mismatches']} mismatches (widths 4, 8, 16).",
      "", "| bits k | n = 2^k − 1 | Peano add rules | binary add bit ops | Peano mul rules | schoolbook mul bit ops |", "|---|---|---|---|---|---|"]
for r in d["unary_vs_binary_cost"][::3]:
    L.append(f"| {r['bits']} | {r['n']} | {r['peano_add_rules']} | {r['binary_add_bit_ops']} | {r['peano_mul_rules'] if r['peano_mul_rules'] is not None else '—'} | {r['binary_school_mul_bit_ops']} |")

d = J("exp002.json")
L += ["", "## GIN-EXP-002 Increment and carries", "",
      f"- Counting 0 → N flips exactly 2N − popcount(N) bits: {d['increment_flips']['mismatches_with_2N_minus_popcount']} mismatches for N ≤ {d['increment_flips']['N_max']}; amortized {d['increment_flips']['amortized_flips_per_increment']:.4f} flips per increment; worst single increment {d['increment_flips']['worst_single_increment']}.",
      "", "| n | mean longest carry chain | log₂ n | difference | max |", "|---|---|---|---|---|"]
for r in d["carry_chains"]:
    L.append(f"| {r['n']} | {r['mean_longest_chain']} | {r['log2_n']} | {r['mean_minus_log2_n']} | {r['max_observed']} |")

d = J("exp003.json")
z = d["zmod_census"]
L += ["", "## GIN-EXP-003 Converse admissibility census", "",
      f"- Z/n, n ≤ 64, all pairs: coset-size violations {z['coset_size_violations']}; unique share = φ(n)/n: {z['unique_share_equals_phi_over_n']}; solvable pairs = Σ n/gcd(b, n): {z['solvable_matches_formula']}.",
      "", "Meaning table (status in each domain):", ""]
doms = d["meaning_table"]["domains"]
L.append("| expression | " + " | ".join(doms) + " |")
L.append("|---" * (len(doms) + 1) + "|")
for e, row in d["meaning_table"]["table"].items():
    L.append(f"| `{e}` | " + " | ".join((v["display"] or v["status"]) if v["status"] in ("value", "special") else v["status"] for v in row.values()) + " |")

d = J("exp004.json")
L += ["", "## GIN-EXP-004 Machine division on this host", "", "Toolchains: " + "; ".join(f"{k}: {v}" for k, v in d["versions"].items()) + ".", "",
      "| behaviour | measured |", "|---|---|"]
c0 = d["c_gcc"]["-O0"]
for k in ("int 1/0", "int INT_MIN/-1", "double 1/0", "double 0/0", "double 1/-0"):
    v = c0[k]
    L.append(f"| C (gcc -O0) `{k}` | {v['signal'] or v['stdout']} |")
for k, v in d["constant_one_over_zero"].items():
    L.append(f"| constant `1/0` — {k} | exit {v['exit']}{', ' + v['signal'] if v['signal'] else ''}: {v['stderr'] or v['stdout']} |")
for k, v in d["c_guard_after_division"].items():
    L.append(f"| `if (b == 0)` after `a / b` — {k} | zero test {'kept' if v['has_compare_or_test'] else 'deleted'} |")
for lang in ("java", "rust_debug", "rust_release", "go"):
    for k, v in d.get(lang, {}).items():
        if "1/0" in k or "MIN" in k:
            L.append(f"| {lang} `{k}` | {v['stdout'] or v['stderr']} |")
for k, v in d.get("javascript", {}).items():
    L.append(f"| JavaScript `{k}` | {v} |")
L.append("")
L.append("Instruction selection (clang -O2): " + "; ".join(f"{t.split('-')[0]}: " + ", ".join(f"{f} → {ins[-2].split()[0] if len(ins) > 1 else ins}" for f, ins in fs.items()) for t, fs in d["instruction_selection"].items()) + ".")
L.append("")
L.append("Model agreement with measurement: " + ", ".join(f"{k}: {'yes' if v else 'NO'}" for k, v in d["model_agreement"].items()) + ".")

d = J("exp005.json")
L += ["", "## GIN-EXP-005 IEEE simulator versus hardware", ""]
for f, v in d["per_format"].items():
    L.append(f"- {f}: {v['random_and_special_cases'] + v['tininess_family_cases']} cases; tininess-after model: {v['tininess_after']['result_mismatches']} result and {v['tininess_after']['flag_mismatches']} flag mismatches; tininess-before model: {v['tininess_before']['flag_mismatches']} flag mismatches (all in the targeted family, where hardware raised underflow in {v['hardware_underflow_flag_in_tininess_family']}/{v['tininess_family_cases']}).")
L.append(f"- Conclusion: this host detects tininess **{d['conclusion_host_tininess']}**.")

d = J("exp006.json")
L += ["", "## GIN-EXP-006 Adder circuits", "",
      "Exhaustive verification n ≤ 8 and random n ∈ {16, 32, 64}: " + str(sum(v["errors"] for r in d["exhaustive"].values() for v in r.values()) + sum(v["errors"] for r in d["random"].values() for v in r.values())) + " errors.", "",
      "| n | ripple gates / depth | Sklansky | Kogge–Stone | Brent–Kung |", "|---|---|---|---|---|"]
for r in d["cost"]:
    L.append(f"| {r['n']} | " + " | ".join(f"{r[k]['gates']} / {r[k]['depth']}" for k in ("ripple-carry", "Sklansky", "Kogge–Stone", "Brent–Kung")) + " |")

d = J("exp007.json")
L += ["", "## GIN-EXP-007 Multiplier and divider circuits", "",
      f"- Exhaustive errors (n ≤ 6): {sum(d['exhaustive_errors'].values())}.",
      "- Zero divisor: restoring divider output equals RISC-V DIVU/REMU (q = 2ⁿ − 1, r = dividend) for every n ≤ 6: " + str(all(v["all_equal_riscv"] for v in d["zero_divisor"].values())) + ".",
      "", "| n | multiplier gates / depth | divider gates / depth |", "|---|---|---|"]
for s in d["sizes"]:
    L.append(f"| {s['n']} | {s['multiplier_gates']} / {s['multiplier_depth']} | {s['divider_gates']} / {s['divider_depth']} |")

d = J("exp008.json")
L += ["", "## GIN-EXP-008 Bit complexity (32-bit limb operations)", "", "| bits | add | mul (school) | mul (Karatsuba) | divmod 2L/L | gcd Euclid | powmod |", "|---|---|---|---|---|---|---|"]
for r in d["rows"]:
    L.append(f"| {r['bits']} | {r['add']} | {r['mul_schoolbook']} | {r['mul_karatsuba']} | {r['divmod_2L_by_L']} | {r.get('gcd_euclid', '—')} | {r.get('powmod_L_bit_exponent', '—')} |")
L.append("")
L.append("Log–log slopes between successive sizes: " + "; ".join(f"{k}: {v[-1] if v else '—'} (last)" for k, v in d["loglog_slopes"].items()) + ".")

d = J("exp009.json")
L += ["", "## GIN-EXP-009 Euclid", "", f"- Lamé: smallest pair for each step count is a consecutive Fibonacci pair: {d['lame']['all_match']} (pairs below {d['lame']['N']}).",
      "- Average steps for prime n versus (12 ln 2/π²) ln n + Porter's constant: " + "; ".join(f"n = {r['n']}: {r['average_steps']} vs {r['prediction']} (diff {r['difference']})" for r in d["average_steps_prime_n"]["rows"]) + ". The difference is −1 up to o(1): Porter's τₙ counts one extra initial step (m mod n with m < n).",
      f"- Bézout coefficient bounds: {d['bezout_bounds']['violations']} violations in {d['bezout_bounds']['samples']} samples."]

d = J("exp010.json")
p = d["pseudoprimes_below_1e6"]
L += ["", "## GIN-EXP-010 Primes", "", f"- Sieve to 10⁶: {d['sieve']['primes']} primes, {d['sieve']['crossings']} crossings ({d['sieve']['ratio']} × n ln ln n).",
      f"- Below 10⁶: {p['fermat_base2']} base-2 Fermat pseudoprimes, {p['strong_base2']} strong base-2 pseudoprimes, {p['carmichael']} Carmichael numbers (published: {p['published']}).",
      f"- Deterministic Miller–Rabin vs sieve: {d['miller_rabin_vs_sieve']['disagreements']} disagreements.",
      "- Pollard rho mean steps / √p: " + ", ".join(f"{r['p_bits']}-bit p: {r['mean_steps_over_sqrt_p']}" for r in d["pollard_rho"]) + "."]

d = J("exp011.json")
L += ["", "## GIN-EXP-011 Numeral evaluation shapes", "", "| digits | Horner | balanced (school) | balanced (Karatsuba) | depth balanced |", "|---|---|---|---|---|"]
for r in d["rows"]:
    L.append(f"| {r['digits']} | {r['horner']} | {r['balanced_schoolbook']} | {r['balanced_karatsuba']} | {r['depth_balanced']} |")
L.append("")
L.append("Last log–log slopes: " + ", ".join(f"{k}: {v[-1]}" for k, v in d["loglog_slopes"].items()) + ".")

d = J("exp012.json")
L += ["", "## GIN-EXP-012 Representation boundaries", "",
      "- Least unrepresentable positive integer: " + "; ".join(f"{k}: {v['least_unrepresentable_found']} (= 2^p + 1: {v['match']})" for k, v in d["least_unrepresentable_integer"].items()) + ".",
      "- Exactly representable k-digit decimals in binary64: " + ", ".join(f"k = {r['digits']}: {r['exactly_representable']} of {r['decimals']}" for r in d["decimal_representability_binary64"]) + ".",
      f"- Associativity of binary64 addition over tenths: {d['associativity']['counterexamples']} of {d['associativity']['triples']} triples fail; commutativity failures: {d['associativity']['commutativity_failures']}.",
      f"- Harmonic sum H₂₀₀₀₀ in binary32: forward {d['harmonic_binary32_n20000']['forward']}, backward {d['harmonic_binary32_n20000']['backward']}, correctly rounded exact {d['harmonic_binary32_n20000']['exact_rounded']}."]

d = J("checks.json")
L += ["", "## Theorem checks (`check_theorems.py`)", "", "| identifier | result | scope |", "|---|---|---|"]
for k, v in d.items():
    L.append(f"| {k} | {'ok' if v['ok'] else 'FAIL'} | {v['detail']} |")
